def best_split(t):
    """Split lowercase token into dictionary words (min-edit DP)."""
    if not t:
        return []
    if t in WORDS:
        return [t]
    n = len(t)
    INF = 10 ** 9
    unk = [INF] * (n + 1)
    words = [INF] * (n + 1)
    back = [None] * (n + 1)
    unk[0] = 0
    words[0] = 0
    for j in range(1, n + 1):
        for i in range(0, j):
            if unk[i] >= INF:
                continue
            frag = t[i:j]
            known = frag in WORDS
            c_unk = unk[i] + (0 if known else len(frag))
            cw = words[i] + 1
            if (c_unk, cw) < (unk[j], words[j]):
                unk[j] = c_unk
                words[j] = cw
                back[j] = (i, known)
    # rebuild
    parts = []
    j = n
    while j > 0 and back[j]:
        i, _ = back[j]
        parts.append(t[i:j])
        j = i
    parts.reverse()
    # merge adjacent unknown fragments
    merged = []
    for p in parts:
        if merged and p not in WORDS and merged[-1] not in WORDS:
            merged[-1] += p
        else:
            merged.append(p)
    return merged or [t]


def pascal(raw):
    if raw is None:
        return "X"
    s = str(raw)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", s)
    s = re.sub(r"[^A-Za-z0-9]+", " ", s)
    parts = []
    for token in s.split():
        if not token:
            continue
        if len(token) > 1 and token[1:].islower() and token[0].isupper():
            words = best_split(token.lower())
        elif token.isupper() or token.islower():
            words = best_split(token.lower())
        else:
            words = best_split(token.lower())
        for w in words:
            if w in RENDERS:
                parts.append(RENDERS[w])
            elif w.isdigit():
                # digits are legal mid-identifier; only escape at the very start
                parts.append(w if parts else "N" + w)
            elif w[0].isdigit():
                m = re.match(r"(\d+)(.*)", w)
                spelled = {str(k): v for k, v in enumerate(
                    ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"])}
                head = "".join(spelled.get(c, c) for c in m.group(1))
                tail = m.group(2)
                parts.append(head + (RENDERS.get(tail, tail.capitalize()) if tail else ""))
            else:
                parts.append(w[0].upper() + w[1:])
    name = "".join(parts) or "X"
    if not name[0].isalpha():
        name = "N" + name
    return name


def doc_lines(text, limit=1800):
    if not text:
        return []
    text = str(text).replace("\r\n", "\n").replace("\r", "\n")
    if len(text) > limit:
        cut = text[:limit]
        last_para = cut.rfind("\n\n")
        if last_para > limit // 2:
            cut = cut[:last_para]
        text = cut.rstrip() + " …"
    out = []
    for line in text.split("\n"):
        line = line.rstrip()
        if line.lstrip().startswith("//"):
            line = line.lstrip()[2:].lstrip()
        out.append("//" + (" " + line if line else ""))
    while out and out[0] == "//":
        out.pop(0)
    while out and out[-1] == "//":
        out.pop()
    return out


