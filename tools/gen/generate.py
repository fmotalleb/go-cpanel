SCALAR = {"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}


class PackageGen:
    def __init__(self, spec, kind):
        self.spec = spec
        self.kind = kind  # 'uapi' | 'whm'
        self.claimed = {}
        self.pending = {}      # name -> dict(def)
        self.pending_order = []
        self.ref_map = {}      # $ref -> go type name
        self.used_methods = set()
        self.flushed = set()   # pending type names already written

    # ---------------- naming ----------------

    def claim(self, base):
        base = base or "X"
        n = self.claimed.get(base, 0)
        self.claimed[base] = n + 1
        return base if n == 0 else f"{base}{n + 1}"

    # ---------------- refs ----------------

    def deref(self, ref):
        node = self.spec
        for part in ref.lstrip("#/").split("/"):
            node = node.get(part, {}) if isinstance(node, dict) else {}
        return node if isinstance(node, dict) else {}

    # ---------------- schema → type ----------------

    def go_type(self, schema, hint, stack=frozenset()):
        if not isinstance(schema, dict) or not schema:
            return "json.RawMessage"
        if "$ref" in schema:
            return self.ref_type(schema["$ref"], hint, stack)
        for combo in ("allOf", "oneOf", "anyOf"):
            if combo in schema:
                got = self.combo_type(schema, combo, hint, stack)
                if got:
                    return got
                return "json.RawMessage"
        t = schema.get("type")
        if t is None:
            if schema.get("properties"):
                return self.emit_object(schema, hint, stack)
            if schema.get("additionalProperties"):
                return self.map_type(schema, hint, stack)
            if schema.get("items"):
                return self.array_go_type(schema, hint, stack)
            if "enum" in schema:
                return "string" if any(isinstance(v, str) for v in schema["enum"]) else "json.RawMessage"
            return "json.RawMessage"
        if isinstance(t, list):
            nonnull = [x for x in t if x != "null"]
            if len(nonnull) != 1:
                return "json.RawMessage"
            schema = dict(schema, type=nonnull[0])
            return self.go_type(schema, hint, stack)
        if t in SCALAR:
            base = SCALAR[t]
            if schema.get("nullable"):
                return "*" + base
            return base
        if t == "array":
            return self.array_go_type(schema, hint, stack)
        if t == "object":
            if schema.get("properties"):
                return self.emit_object(schema, hint, stack)
            if schema.get("additionalProperties"):
                return self.map_type(schema, hint, stack)
            return "json.RawMessage"
        return "json.RawMessage"

    def ref_type(self, ref, hint, stack):
        if ref in self.ref_map:
            return self.ref_map[ref]
        if ref in stack:
            return "json.RawMessage"
        name = self.claim(pascal(ref.rsplit("/", 1)[-1]))
        self.ref_map[ref] = name
        target = self.deref(ref)
        body = self.type_body(target, name, stack | {ref})
        self.add_pending(name, body, target.get("description", "") if isinstance(target, dict) else "")
        return name

    def type_body(self, schema, name, stack):
        """Return a definition dict for a named type."""
        if not isinstance(schema, dict):
            return {"kind": "raw"}
        for combo in ("allOf", "oneOf", "anyOf"):
            if combo in schema:
                merged = self.merge_combo(schema, combo, stack)
                if merged is not None:
                    return merged
                return {"kind": "raw"}
        if schema.get("properties"):
            return self.struct_body(schema, name, stack)
        t = schema.get("type")
        if t == "array":
            inner = self.go_type(schema.get("items") or {}, name + "Item", stack)
            return {"kind": "alias", "type": f"[]{inner}"}
        if t == "object" and schema.get("additionalProperties"):
            inner = self.go_type(schema.get("additionalProperties") or {}, name + "Value", stack)
            return {"kind": "alias", "type": f"map[string]{inner}"}
        return {"kind": "raw"}

    def merge_combo(self, schema, combo, stack):
        for v in schema[combo]:
            b = self.deref(v["$ref"]) if (isinstance(v, dict) and "$ref" in v) else v
            if not isinstance(b, dict) or not (b.get("properties") or b.get("type") == "object"):
                return None
        props = {}
        required = []
        for v in schema[combo]:
            b = self.deref(v["$ref"]) if (isinstance(v, dict) and "$ref" in v) else v
            props.update(b.get("properties") or {})
            required += b.get("required") or []
        return {"kind": "struct_from",
                "schema": {"type": "object", "properties": props, "required": required}}

    def combo_type(self, schema, combo, hint, stack):
        variants = schema[combo]
        if combo == "allOf":
            merged = self.merge_combo(schema, combo, stack)
            if merged:
                return self.emit_named(merged, hint, schema.get("description", ""), stack)
            return None
        types = set()
        for v in variants:
            b = self.deref(v["$ref"]) if (isinstance(v, dict) and "$ref" in v) else v
            if not isinstance(b, dict):
                return None
            t = b.get("type")
            if t is None:
                t = "object" if b.get("properties") else ("array" if b.get("items") else "string")
            types.add(t)
        types.discard("null")
        if len(types) == 1:
            t = types.pop()
            if t in SCALAR:
                base = SCALAR[t]
                if schema.get("nullable"):
                    return "*" + base
                return base
            if t == "array":
                inner_types = set()
                for v in variants:
                    b = self.deref(v["$ref"]) if (isinstance(v, dict) and "$ref" in v) else v
                    it = (b.get("items") or {}).get("type", "string")
                    inner_types.add(SCALAR.get(it, "string"))
                if len(inner_types) == 1:
                    return "[]" + inner_types.pop()
                return None
        if types and types <= set(SCALAR):
            return "any"
        return None

    def emit_named(self, body, hint, doc, stack):
        name = self.claim(pascal(hint))
        if body.get("kind") == "struct_from":
            body = self.struct_body(body["schema"], name, stack)
        self.add_pending(name, body, doc)
        return name

    def emit_object(self, schema, hint, stack):
        name = self.claim(pascal(hint))
        body = self.struct_body(schema, name, stack)
        self.add_pending(name, body, schema.get("description", ""))
        return name

    def array_go_type(self, schema, hint, stack):
        items = schema.get("items")
        if not isinstance(items, dict) or not items or items == {}:
            return "[]json.RawMessage"
        inner = self.go_type(items, hint + "Item", stack)
        if inner == "json.RawMessage":
            return "[]json.RawMessage"
        if inner == "any":
            return "[]any"
        return f"[]{inner}"

    def map_type(self, schema, hint, stack):
        addl = schema.get("additionalProperties")
        if not isinstance(addl, dict) or not addl:
            return "map[string]json.RawMessage"
        inner = self.go_type(addl, hint + "Value", stack)
        if inner == "json.RawMessage":
            return "map[string]json.RawMessage"
        return f"map[string]{inner}"

    def struct_body(self, schema, owner_name, stack):
        fields = []
        used = set()
        props = schema.get("properties") or {}
        for pname in sorted(props):
            pschema = props[pname] if isinstance(props[pname], dict) else {}
            fname = unique(pascal_field(pname), used)
            ftype = self.go_type(pschema, owner_name + fname, stack)
            nullable = pschema.get("nullable") and ftype in ("string", "int64", "float64", "bool")
            if nullable:
                ftype = "*" + ftype
            doc = pschema.get("description", "")
            if pschema.get("enum"):
                enum_vals = ", ".join("`%s`" % v for v in pschema["enum"])
                doc = (doc + "\n\nPossible values: " + enum_vals + ".") if doc else "Possible values: " + enum_vals + "."
            fields.append({"name": fname, "type": ftype, "tag": pname, "doc": doc})
        return {"kind": "struct", "fields": fields}

    def add_pending(self, name, body, doc):
        if name in self.pending:
            return
        body["doc"] = body.get("doc") or doc or ""
        self.pending[name] = body
        self.pending_order.append(name)

    # ---------------- params ----------------

    def param_go_type(self, pschema):
        if not isinstance(pschema, dict):
            return "string"
        if "$ref" in pschema:
            pschema = self.deref(pschema["$ref"])
        for combo in ("oneOf", "anyOf", "allOf"):
            if combo in pschema:
                types = set()
                for v in pschema[combo]:
                    b = self.deref(v["$ref"]) if (isinstance(v, dict) and "$ref" in v) else v
                    if not isinstance(b, dict):
                        continue
                    t = b.get("type")
                    if t is None:
                        t = "object" if b.get("properties") else ("array" if b.get("items") else "string")
                    types.add(t)
                types.discard("null")
                if len(types) == 1:
                    t = types.pop()
                    if t == "array":
                        return "[]string", False
                    if t in SCALAR:
                        return SCALAR[t], bool(pschema.get("nullable"))
                if types and types <= set(SCALAR):
                    return "any", False
                return "json.RawMessage", False
        t = pschema.get("type")
        if t == "array":
            it = pschema.get("items") or {}
            it_t = it.get("type", "string")
            elem = SCALAR.get(it_t, "string")
            return f"[]{elem}", False
        if t in SCALAR:
            return SCALAR[t], bool(pschema.get("nullable"))
        if t == "object":
            return "map[string]string", False
        return "string", False


def unique(name, used):
    base, i = name, 2
    while name in used or name.lower() in GO_KEYWORDS:
        name = f"{base}{i}"
        i += 1
    used.add(name)
    return name


def pascal_field(raw):
    n = pascal(raw)
    if not n or not n[0].isalpha():
        n = "X" + n
    return n


