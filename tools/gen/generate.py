def extract_data_schema(op):
    resp = (op.get("responses") or {}).get("200") or {}
    content = (resp.get("content") or {}).get("application/json") or {}
    schema = content.get("schema") or {}
    props = schema.get("properties") or {}
    if "result" in props and isinstance(props["result"], dict):
        rprops = props["result"].get("properties") or {}
        if "data" in rprops:
            return rprops["data"]
    if "data" in props:
        return props["data"]
    return None


def build_doc_index(md_path):
    out = {}
    if not md_path:
        return out
    p = Path(md_path)
    if not p.exists():
        return out
    rx = re.compile(r"\[(GET|POST) (/[^\]]+)\]\((https://api\.docs\.cpanel\.net/[^)]+)\)")
    for line in p.read_text(encoding="utf-8").splitlines():
        m = rx.search(line)
        if m:
            out[(m.group(1), m.group(2))] = m.group(3)
    return out


def parse_ops(spec, kind, doc_urls):
    ops = []
    for path, item in sorted(spec["paths"].items()):
        for method, op in item.items():
            if method not in ("get", "post"):
                continue
            segs = path.strip("/").split("/")
            module = segs[0] if kind == "uapi" else None
            fn_name = segs[-1]
            tags = op.get("tags") or []
            category = tags[0] if tags else "Miscellaneous"
            ops.append({
                "path": path,
                "method": method,
                "module": module,
                "category": category if kind == "whm" else None,
                "function": fn_name,
                "summary": (op.get("summary") or "").strip(),
                "description": (op.get("description") or "").strip(),
                "deprecated": bool(op.get("deprecated")),
                "since": op.get("x-cpanel-available-version", "") or "",
                "params": op.get("parameters") or [],
                "data_schema": extract_data_schema(op),
                "doc_url": doc_urls.get((method.upper(), path), ""),
            })
    return ops


