def write_doc(outdir, pkg, head, groups, url):
    counts = ", ".join(f"{k} ({len(v)})" for k, v in sorted(groups.items(), key=lambda kv: str(kv[0]).lower()))
    lines = [
        HEADER,
        "",
    ]
    for dl in doc_lines(head, limit=400):
        lines.append(dl)
    lines.append("//")
    lines.append(f"// Official documentation: {url}")
    lines.append("//")
    lines.append("// Groups and function counts:")
    lines.append("//")
    for dl in doc_lines(counts, limit=6000):
        lines.append(dl)
    lines.append(f"package {pkg}")
    p = outdir / "doc.go"
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


def run_gofmt(paths):
    exe = shutil.which("gofmt")
    if exe is None:
        print("warning: gofmt not found on PATH; generated files were left "
              "unformatted (run `gofmt -w .` afterwards)", file=sys.stderr)
        return
    subprocess.run([exe, "-w", *(str(p) for p in paths)], check=True)
    print(f"gofmt: formatted {len(paths)} generated files")


if __name__ == "__main__":
    main()
