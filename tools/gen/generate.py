def emit_type_def(lines, name, body):
    kind = body["kind"]
    doc = (body.get("doc") or "").strip()
    if doc:
        for dl in doc_lines(doc, limit=500):
            lines.append(dl)
    else:
        lines.append(f"// {name} is a generated payload type.")
    if kind == "struct":
        lines.append(f"type {name} struct {{")
        if not body["fields"]:
            lines.append("}")
            lines.append("")
            return
        # compute alignment
        maxn = max(len(f["name"]) for f in body["fields"])
        for f in body["fields"]:
            for dl2 in doc_lines(f.get("doc", ""), limit=400):
                lines.append("\t" + dl2)
            tag = f'`json:"{f["tag"]}"`'
            lines.append(f"\t{f['name'].ljust(maxn + 1)}{f['type']} {tag}")
            lines.append("")
        if lines and lines[-1] == "":
            lines.pop()
        lines.append("}")
    elif kind == "alias":
        lines.append(f"type {name} {body['type']}")
    else:
        lines.append(f"// {name} is left as raw JSON because its documented schema")
        lines.append("// is a union of shapes; inspect it with encoding/json.")
        lines.append(f"type {name} = json.RawMessage")
    lines.append("")


def emit_param_doc(param, required):
    bits = []
    desc = (param.get("description") or "").strip()
    sch = param.get("schema") or {}
    if sch.get("enum"):
        desc += ("\n\nPossible values: " + ", ".join("`%s`" % v for v in sch["enum"]) + ".")
    if "default" in sch:
        desc += f"\n\nDefaults to `{sch['default']}`."
    if sch.get("format") and len(str(sch["format"])) < 30:
        pass
    dl = doc_lines(desc, limit=500)
    bits.extend(dl)
    if required:
        bits.append("//")
        bits.append("// This parameter is required.")
    return bits


def slugify_file(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "misc"


def generate_package(kind, spec, ops, outdir, pkg_doc, spec_root):
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    gen = PackageGen(spec, kind)

    # group ops
    groups = {}
    for op in ops:
        key = op["module"] if kind == "uapi" else op["category"]
        groups.setdefault(key, []).append(op)

    files = {}  # filename -> code lines
    for gkey in sorted(groups, key=str.lower):
        ops_list = groups[gkey]
        lines = []
        for op in ops_list:
            emit_op(lines, gen, kind, gkey, op, spec_root)
        fname = f"zz_{slugify_file(gkey)}_gen.go"
        files[fname] = lines

    # any late-created payload types (shouldn't happen, but be safe)
    written = []
    for fname, lines in files.items():
        code = assemble_file(gen, kind, fname, lines)
        p = outdir / fname
        p.write_text(code, encoding="utf-8")
        written.append(p)

    return gen, groups, written


def pkg_name(kind):
    return "uapi" if kind == "uapi" else "whm"


def assemble_file(gen, kind, fname, lines):
    used_json = any("json.RawMessage" in ln or "json." in ln for ln in lines)
    imports = ['"context"', '"net/http"', '']
    if used_json:
        imports.insert(1, '"encoding/json"')
    imports.append(f'cpanel "github.com/fmotalleb/go-cpanel"')
    code = HEADER + f"\npackage {pkg_name(kind)}\n\nimport (\n"
    for imp in imports:
        code += f"\t{imp}\n" if imp else "\n"
    code += ")\n\n"
    code += "\n".join(lines)
    return code


def emit_op(lines, gen, kind, gkey, op, spec_root):
    module = op["module"]
    category = op["category"]
    fn = op["function"]
    method = op["method"]
    if kind == "uapi":
        type_base = f"{pascal(module)}__M__"
        call_fn = "cpanel.UAPICall"
        result_t = "cpanel.UAPIResult"
        call_args = f'ctx, c.c, http.Method{"Get" if method == "get" else "Post"}, "{module}", "{fn}", '
        api_label = f'UAPI function `{module}::{fn}`'
    else:
        type_base = "__M__"
        call_fn = "cpanel.WHMCall"
        result_t = "cpanel.WHMResult"
        call_args = f'ctx, c.c, http.Method{"Get" if method == "get" else "Post"}, "{fn}", '
        api_label = f'WHM API 1 function `{fn}`'

    method_name = pascal(fn)
    mkey = method_name if kind == "whm" else f"{gkey}::{method_name}"
    suffix = 2
    while mkey in gen.used_methods:
        method_name = f"{pascal(fn)}{suffix}"
        mkey = method_name if kind == "whm" else f"{gkey}::{method_name}"
        suffix += 1
    gen.used_methods.add(mkey)
    receiver = f"(c *{pascal(gkey)}Client)" if kind == "uapi" else "(c *Client)"

    type_base = type_base.replace("__M__", method_name)

    # --- data type
    ds = op["data_schema"]
    if ds:
        data_type = gen.go_type(ds, type_base + "Data")
    else:
        data_type = "json.RawMessage"

    # --- args struct
    params = op["params"] or []
    args_type = None
    if params:
        args_type = gen.claim(type_base + "Args")
        for dl in doc_lines(f"{args_type} are the parameters of the {api_label}.", limit=200):
            lines.append(dl)
        lines.append(f"type {args_type} struct {{")
        used_fields = set()
        field_rows = []
        for p in params:
            pname = p.get("name", "")
            if not pname:
                continue
            required = bool(p.get("required"))
            sch = p.get("schema") or {}
            gtype, nullable = gen.param_go_type(sch)
            if not required and gtype in ("string", "int64", "float64", "bool"):
                gtype = "*" + gtype
            fname = unique(pascal_field(pname), used_fields)
            tagopt = "" if required else ",omitempty"
            tag = f'`cpanel:"{pname}{tagopt}"`'
            pdoc = emit_param_doc(p, required)
            field_rows.append((fname, gtype, tag, pdoc))
        for fname, gtype, tag, pdoc in field_rows:
            for dl in pdoc:
                lines.append("\t" + dl)
            lines.append(f"\t{fname} {gtype} {tag}")
            lines.append("")
        for dl in doc_lines("Extra carries any additional arguments (e.g. UAPI/WHM meta arguments such as api.filter.*, api.sort.*, api.paginate.*).", limit=300):
            lines.append("\t" + dl)
        lines.append("\tExtra cpanel.Args `cpanel:\"-\"`")
        if lines and lines[-1] == "":
            lines.pop()
        lines.append("}")
        lines.append("")

    # --- method
    summary = op["summary"] or f"{api_label}."
    desc = op["description"]
    doc = f"{method_name} calls the {api_label} — {summary}"
    for dl in doc_lines(doc, limit=300):
        lines.append(dl)
    if desc:
        lines.append("//")
        for dl in doc_lines(desc, limit=1500):
            lines.append(dl)
    meta_bits = []
    if method == "post":
        meta_bits.append("This function requires an HTTP POST request.")
    if op["deprecated"]:
        meta_bits.append("This function is deprecated upstream.")
    if op["since"]:
        meta_bits.append(f"Available since cPanel & WHM version {op['since']}.")
    url = op["doc_url"] or spec_root
    meta_bits.append(f"Documentation: {url}")
    lines.append("//")
    for dl in doc_lines("\n\n".join(meta_bits), limit=900):
        lines.append(dl)
    if op["deprecated"]:
        lines.append("//")
        lines.append("// Deprecated: cPanel & WHM mark this function as deprecated.")

    sig_ret = f"(*{result_t}[{data_type}], error)"
    if args_type:
        sig = f"func {receiver} {method_name}(ctx context.Context, args *{args_type}) {sig_ret} {{"
        body = f"\treturn {call_fn}[{data_type}]({call_args}args)"
    else:
        sig = f"func {receiver} {method_name}(ctx context.Context, extra ...cpanel.Args) {sig_ret} {{"
        body = f"\treturn {call_fn}[{data_type}]({call_args}cpanel.CombineArgs(extra...))"
    lines.append(sig)
    lines.append(body)
    lines.append("}")
    lines.append("")
    lines.append("")

    # flush newly-created pending payload types into this file
    flush = []
    for name in gen.pending_order:
        if name in gen.flushed:
            continue
        emit_type_def(flush, name, gen.pending[name])
        gen.flushed.add(name)
    lines.extend(flush)


def collect_identifiers(spec, out):
    def walk(node):
        if isinstance(node, dict):
            for k, v in node.items():
                if k in ("name",):
                    extract(v)
                elif k == "properties" and isinstance(v, dict):
                    for prop in v:
                        extract(prop)
                walk(v)
        elif isinstance(node, list):
            for i in node:
                walk(i)
    def extract(v):
        if not isinstance(v, str):
            return
        v2 = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", v)
        toks = [t for t in re.split(r"[^A-Za-z0-9]+", v2) if t]
        SHORT_OK = {"id", "in", "is", "it", "ip", "mx", "my", "no", "ns", "of", "on", "or",
                    "os", "so", "to", "up", "us", "am", "an", "as", "at", "be", "by", "do", "go", "ok", "we"}
        if len(toks) > 1:
            # a token separated by underscores/camel humps is evidenced as a real word
            for tok in toks:
                tok = tok.strip().lower()
                if not tok.isalpha():
                    continue
                if len(tok) == 2 and tok not in SHORT_OK:
                    continue
                if 3 <= len(tok) <= 16:
                    out.add(tok)
        elif toks:
            # whole identifiers are suspect (may be joined words); only short ones
            tok = toks[0].strip().lower()
            if tok.isalpha() and 2 <= len(tok) <= 8:
                if len(tok) == 2 and tok not in SHORT_OK:
                    return
                out.add(tok)
    for path in spec.get("paths", {}):
        extract(path)
    for name in (spec.get("components", {}).get("schemas", {}) or {}):
        extract(name)
    walk(spec)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cpanel_yaml")
    ap.add_argument("whm_yaml")
    ap.add_argument("outdir")
    ap.add_argument("--cpanel-md")
    ap.add_argument("--whm-md")
    args = ap.parse_args()

    outdir = Path(args.outdir)

    cpanel_spec = yaml.safe_load(Path(args.cpanel_yaml).read_text())
    whm_spec = yaml.safe_load(Path(args.whm_yaml).read_text())
    idents = set()
    collect_identifiers(cpanel_spec, idents)
    collect_identifiers(whm_spec, idents)
    WORDS.update(idents)
    WORDS.difference_update(BANNED)
    cpanel_urls = build_doc_index(args.cpanel_md)
    whm_urls = build_doc_index(args.whm_md)

    uapi_ops = parse_ops(cpanel_spec, "uapi", cpanel_urls)
    whm_ops = parse_ops(whm_spec, "whm", whm_urls)

    ug, ugroups, uwritten = generate_package("uapi", cpanel_spec, uapi_ops, outdir / "uapi",
                                             "", "https://api.docs.cpanel.net/specifications/cpanel.openapi")
    wg, wgroups, wwritten = generate_package("whm", whm_spec, whm_ops, outdir / "whm",
                                             "", "https://api.docs.cpanel.net/specifications/whm.openapi")

    # client scaffolding
    written = uwritten + wwritten
    written.append(write_uapi_client(outdir / "uapi", sorted(ugroups.keys(), key=str.lower)))
    written.append(write_whm_client(outdir / "whm"))
    written.append(write_doc(outdir / "uapi", "uapi", "Package uapi provides fully-typed access to every cPanel UAPI\nfunction documented in cPanel's official OpenAPI document (version 138):",
                             ugroups, "https://api.docs.cpanel.net/specifications/cpanel.openapi"))
    written.append(write_doc(outdir / "whm", "whm", "Package whm provides fully-typed access to every WHM API 1\nfunction documented in cPanel's official OpenAPI document (version 138):",
                             wgroups, "https://api.docs.cpanel.net/specifications/whm.openapi"))
    run_gofmt(written)

    total = len(uapi_ops) + len(whm_ops)
    print(f"uapi: {len(uapi_ops)} functions in {len(ugroups)} modules")
    print(f"whm : {len(whm_ops)} functions in {len(wgroups)} categories")
    print(f"total: {total} functions")


def write_uapi_client(outdir, modules):
    lines = [HEADER,
             "// Package uapi contains typed wrappers for every cPanel UAPI function.",
             "package uapi",
             "",
             "import (",
             '\tcpanel "github.com/fmotalleb/go-cpanel"',
             ")",
             "",
             "// Client is the entry point of the typed cPanel UAPI API.",
             "//",
             "// Obtain one with New; module accessors return the per-module clients,",
             "// for example c.Email().AddPop(...). The zero value is not usable.",
             "type Client struct { c *cpanel.Client }",
             "",
             "// New wraps a core cpanel.Client (pointed at a cPanel server,",
             "// typically https://host:2083) with typed UAPI access.",
             "func New(c *cpanel.Client) *Client { return &Client{c: c} }",
             "",
             "// Core returns the underlying core client.",
             "func (c *Client) Core() *cpanel.Client { return c.c }",
             ""]
    for m in modules:
        t = f"{pascal(m)}Client"
        lines.append("")
        lines.append(f"// {t} wraps calls to the UAPI `{m}` module.")
        lines.append(f"type {t} struct {{ c *cpanel.Client }}")
        lines.append("")
        lines.append(f"// {pascal(m)} returns the client for the UAPI `{m}` module.")
        lines.append(f"func (c *Client) {pascal(m)}() *{t} {{ return &{t}{{c: c.c}} }}")
    p = outdir / "client.go"
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


